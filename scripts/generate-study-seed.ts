import { writeFileSync } from "node:fs";
import { course } from "../src/course/model";
import { quizQuestion } from "../src/course/quiz";
const quote = (v: string) => `'${v.replaceAll("'", "''")}'`;
const topics = course.map(
  (t) => `(${quote(t.id)},${t.pages.length},${t.practice.count})`,
);
const questions = course.flatMap((t) =>
  Array.from({ length: t.practice.count }, (_, i) => {
    const q = quizQuestion(t.id, String(i + 1));
    if (!q.choices.some((c) => c.id === 0))
      throw Error(`Missing authored answer: ${t.id}/${i + 1}`);
    return `(${quote(t.id)},${i + 1},0)`;
  }),
);
writeFileSync(
  "supabase/study-seed.sql",
  `-- Authored course catalog only; no user data. Generated by scripts/generate-study-seed.ts.\ninsert into public.study_topics(id,page_count,question_count) values\n${topics.join(",\n")}\non conflict(id) do update set page_count=excluded.page_count,question_count=excluded.question_count;\ninsert into public.study_questions(topic_id,question_no,correct_choice) values\n${questions.join(",\n")}\non conflict(topic_id,question_no) do update set correct_choice=excluded.correct_choice;\n`,
);
console.log(`${topics.length} topics / ${questions.length} question keys`);

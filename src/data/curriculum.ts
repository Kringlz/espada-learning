const q = (
  id: string,
  prompt: string,
  correct: number | string,
  wrong: (number | string)[],
  explanation: string,
  hint: string,
): Question => {
  const options = [String(correct), ...wrong.map(String)];
  const shift = id.charCodeAt(id.length - 1) % 4;
  return {
    id,
    prompt,
    choices: [...options.slice(shift), ...options.slice(0, shift)],
    answer: (4 - shift) % 4,
    explanation,
    hint,
  };
};

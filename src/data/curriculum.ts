export const originalCurriculum: Topic[] = specs.map(
  ([id, title, area, prerequisites, objective, lesson, example, make]) => ({
    id,
    title,
    area,
    prerequisites,
    objective,
    lesson,
    example,
    minutes: 8,
    practice: make(0, `${id}-guided`),
    checks: Array.from({ length: 6 }, (_, i) =>
      make(i + 1, `${id}-check-${i + 1}`),
    ),
  }),
);

// Stable IDs preserve all prior attempts and paper evidence.
const mapped: Record<number, string> = {
  1: "place-value",
  6: "operations",
  9: "angles",
  10: "perimeter",
  14: "equations",
  23: "equivalent",
  25: "add-fractions",
  32: "averages",
  34: "ratios",
};
export const curriculum: Topic[] = sections.flatMap((section) =>
  section.titles.map((title, i) => {
    const order = section.start + i;
    const existing = originalCurriculum.find((t) => t.id === mapped[order]);
    return {
      ...(existing ?? {
        id: `math-${String(order).padStart(3, "0")}`,
        area: section.area,
        prerequisites: [],
        objective: "",
        lesson: "",
        example: "",
        minutes: 0,
        checks: [],
      }),
      title,
      sectionId: section.id,
      order,
    };
  }),
);
curriculum.push(
  ...originalCurriculum.filter((t) => !Object.values(mapped).includes(t.id)),
);

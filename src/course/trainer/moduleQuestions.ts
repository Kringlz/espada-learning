function draft(skill: string, v: number): FamilyDraft {
  const a = 2 + (v % 6),
    b = 2 + (Math.floor(v / 6) % 3);
  const n = (
    prompt: string,
    answer: number,
    errors: number[],
    solution: string,
    hint: string,
  ) => numeric("@" + skill, 1, prompt, answer, errors, solution, hint);
  if (facts[skill]) {
    const [prompt, choices, solution] = facts[skill][v % facts[skill].length];
    return {
      skill: "@" + skill,
      difficulty: v % 2 ? 2 : 1,
      prompt,
      choices,
      solution,
      hint: solution,
    };
  }
  switch (skill) {
    case "place-value":
      return n(
        `Сколько обозначает цифра ${a} в числе ${a}05?`,
        a * 100,
        [a, a * 10, 0],
        `${a} стоит в разряде сотен: ${a} · 100 = ${a * 100}.`,
        "Прочитай разряд цифры.",
      );
    case "joint-time":
      return n(
        `Два мастера делают ${a} и ${b} деталей в час. За сколько часов они вместе сделают ${(a + b) * 3} деталей?`,
        3,
        [a + b, a + b + 1, 1],
        `Общая производительность ${a + b}. Время: ${(a + b) * 3} : ${a + b} = 3 ч.`,
        "Раздели работу на общую производительность.",
      );
    case "signed-compare":
      return {
        skill: "@" + skill,
        difficulty: 1,
        prompt: `Какое число больше −${a}?`,
        choices: [`−${a - 1}`, `−${a + 1}`, `−${a + 2}`, `−${a + 3}`],
        solution: `−${a - 1} ближе к нулю и правее −${a}.`,
        hint: "Сравни положение на числовой прямой.",
      };
    case "angle-measure":
      return n(
        `Стороны угла на одной шкале транспортира проходят через ${a * 10}° и ${a * 10 + 40}°. Чему равен угол в градусах?`,
        40,
        [a * 10 + 40, a * 10 + 80, 180],
        `Разность показаний: ${a * 10 + 40} − ${a * 10} = 40°.`,
        "Найди разность отсчётов.",
      );
    case "divisibility-last":
      return {
        skill: "@" + skill,
        difficulty: 1,
        prompt: `Какое число делится на 5, но не на 10?`,
        choices: [`${a}5`, `${a}0`, `${a}2`, `${a}3`],
        solution:
          "Число должно оканчиваться на 5. Конечный ноль дал бы делимость на 10.",
        hint: "Проверь последнюю цифру.",
      };
    case "divisibility-sum":
      return {
        skill: "@" + skill,
        difficulty: 1,
        prompt: "Какое число делится на 9?",
        choices: ["234", "235", "236", "238"],
        solution: "2 + 3 + 4 = 9, сумма цифр делится на 9.",
        hint: "Сложи цифры.",
      };
    case "fraction-subtract":
      return {
        skill: "@" + skill,
        difficulty: 1,
        prompt: `Вычисли ${a + 2}/${a + 3} − ${a}/${a + 3}.`,
        choices: [
          `2/${a + 3}`,
          `2/${2 * (a + 3)}`,
          `${2 * a + 2}/${a + 3}`,
          `1/${a + 3}`,
        ],
        solution: `Вычитаем числители: ${a + 2} − ${a} = 2. Знаменатель ${a + 3} не меняется.`,
        hint: "У дробей общий знаменатель.",
      };
    case "mixed-number":
      return {
        skill: "@" + skill,
        difficulty: 1,
        prompt: `Запиши ${a} 1/3 неправильной дробью.`,
        choices: [
          `${3 * a + 1}/3`,
          `${a + 1}/3`,
          `${3 * a}/3`,
          `${3 * a - 1}/3`,
        ],
        solution: `${a} целых — это ${3 * a} третьих. Добавляем одну треть.`,
        hint: "Умножь целую часть на знаменатель и прибавь числитель.",
      };
    case "decimal-place":
      return n(
        `В числе 0,${a}7 сколько десятых показывает цифра ${a}?`,
        a,
        [a + 1, a * 10, 100],
        `Первый разряд после запятой — десятые. Их ${a}.`,
        "Определи положение цифры после запятой.",
      );
    case "decimal-compare":
      return {
        skill: "@" + skill,
        difficulty: 1,
        prompt: `Какое число больше 0,${a}5?`,
        choices: [`0,${a}6`, `0,${a}4`, `0,${a}05`, `0,0${a}`],
        solution: `Целые и десятые равны; 6 сотых больше 5 сотых.`,
        hint: "Сравни разряды по очереди.",
      };
    case "percent-ratio":
      return n(
        `Из ${a * 10} заданий решены ${a * 3}. Сколько процентов решено?`,
        30,
        [3, 70, 10],
        `${a * 3}/${a * 10} · 100% = 30%.`,
        "Раздели часть на целое.",
      );
    case "rational-product":
      return {
        skill: "@" + skill,
        difficulty: 1,
        prompt: `Упрости (${a}/x) · (x/${a + 1}), x ≠ 0.`,
        choices: [
          `${a}/${a + 1}`,
          `${a + 1}/${a}`,
          `${a}x/${a + 1}`,
          `${a}/(${a + 1}x²)`,
        ],
        solution: `Перемножаем числители и знаменатели, сокращаем ненулевой множитель x.`,
        hint: "Сокращай множители, а не слагаемые.",
      };
    case "root-simplify":
      return {
        skill: "@" + skill,
        difficulty: 1,
        prompt: `Упрости √${3 * a * a}.`,
        choices: [`${a}√3`, `${a * 3}`, `${a * a}√3`, `${a + 1}√3`],
        solution: `${3 * a * a} = ${a * a} · 3. Корень из ${a * a} равен ${a}.`,
        hint: "Выдели полный квадрат.",
      };
    case "polygon-angles":
      return n(
        `Чему равна сумма внутренних углов выпуклого ${a + 3}-угольника в градусах?`,
        (a + 1) * 180,
        [(a + 3) * 180, 360, (a + 2) * 180],
        `(n − 2) · 180° = ${a + 1} · 180° = ${(a + 1) * 180}°.`,
        "Разбей многоугольник на треугольники из одной вершины.",
      );
    case "rectangle-diagonal":
      return n(
        `Диагональ прямоугольника равна ${2 * a}. Чему равен отрезок от вершины до точки пересечения диагоналей?`,
        a,
        [a * 2, a * 4, a + 1],
        `Диагонали прямоугольника делятся пополам: ${a * 2} : 2 = ${a}.`,
        "Найди половину диагонали.",
      );
    case "trapezoid-midline":
      return n(
        `Основания трапеции ${a} и ${a + 4}. Найди среднюю линию.`,
        a + 2,
        [a * 2 + 4, a, a + 4],
        `(${a} + ${a + 4})/2 = ${a + 2}.`,
        "Возьми полусумму оснований.",
      );
    case "vector-subtract":
      return {
        skill: "@" + skill,
        difficulty: 1,
        prompt: `Найди (${a}; 5) − (1; 2).`,
        choices: [
          `(${a - 1}; 3)`,
          `(${a + 1}; 7)`,
          `(${a - 1}; 7)`,
          `(${a + 1}; 3)`,
        ],
        solution: `Вычитаем координаты: (${a}−1; 5−2).`,
        hint: "Работай с каждой координатой отдельно.",
      };
    case "vector-scale":
      return {
        skill: "@" + skill,
        difficulty: 1,
        prompt: `Умножь вектор (${a}; −1) на −2.`,
        choices: [
          `(−${a * 2}; 2)`,
          `(${a * 2}; −2)`,
          `(−${a * 2}; −1)`,
          `(${a}; 2)`,
        ],
        solution: "Умножаем обе координаты на −2. Минус на минус даёт плюс.",
        hint: "Множитель действует на обе координаты.",
      };
    case "vector-length":
      return n(
        `Найди длину вектора (${3 * a}; ${4 * a}).`,
        5 * a,
        [7 * a, a, 25 * a],
        `√((${3 * a})² + (${4 * a})²) = ${5 * a}.`,
        "Примени теорему Пифагора.",
      );
    case "vertical-shift":
      return n(
        `График y = x² сдвинули вверх на ${a}. Каково значение новой функции при x = 0?`,
        a,
        [0, -a, a * a],
        `Новая функция y = x² + ${a}. При x=0 получаем ${a}.`,
        "Сдвиг вверх прибавляет число к значению функции.",
      );
    case "function-scale":
      return n(
        `При x = 2 функция f принимает значение ${a}. Чему равно 3f(2)?`,
        3 * a,
        [a, a + 3, a * a + 3],
        `Все значения функции умножаются на 3: 3 · ${a} = ${3 * a}.`,
        "Множитель стоит перед функцией.",
      );
    case "log-power":
      return n(
        `Чему равно log₂(2^${a})?`,
        a,
        [2 ** a, 2 ** a + 1, 0],
        `Логарифм и возведение в степень с одинаковым основанием взаимно обратны.`,
        "В какую степень возвели 2?",
      );
    case "prism-surface":
      return n(
        `У прямой призмы периметр основания ${a * 4} см, высота ${b} см. Найди боковую площадь в см².`,
        a * 4 * b,
        [a * 4 + b, a * 4, a * b],
        `Боковая площадь = периметр основания · высота: ${a * 4} · ${b}.`,
        "Развёртка боковой поверхности — прямоугольник.",
      );
    case "cone-volume":
      return n(
        `Радиус конуса ${a}, высота 3. Найди V/π.`,
        a * a,
        [3 * a * a, a * a * 2, a],
        `V = πr²h/3 = π · ${a * a} · 3/3 = ${a * a}π.`,
        "Учти множитель 1/3.",
      );
    case "sphere-volume":
      return n(
        `Радиус шара увеличили в ${a} раза. Во сколько раз увеличился объём?`,
        a ** 3,
        [a, a * a, 3 * a + 1],
        `Объём пропорционален кубу радиуса: ${a}³ = ${a ** 3}.`,
        "В формуле объёма радиус стоит в третьей степени.",
      );
    default:
      throw Error(`Missing module skill: ${skill}`);
  }
}
const cache = new Map<string, Question[]>();
export function moduleSkillBank(topic: string, skill: string): Question[] {
  const key = topic + ":" + skill;
  if (!cache.has(key)) {
    const unique = new Map<string, Question>();
    for (let i = 0; i < 12; i++) {
      const d = draft(skill.replace(/^@/, ""), i);
      const q: Question = {
        ...d,
        id: `${topic}-module-v1-${skill.slice(1)}-${i}`,
        correct: 0,
        concept: topic,
        hints: [d.hint],
        source:
          "Собственная задача Espada по материалам конспекта и справочника; модульный банк v1.",
      };
      const signature = JSON.stringify([q.prompt, [...q.choices].sort()]);
      if (!unique.has(signature)) unique.set(signature, q);
    }
    cache.set(key, [...unique.values()]);
  }
  return cache.get(key)!;
}

import { counted, type FamilyDraft } from "./qualityTypes";

function task(
  skill: string,
  difficulty: 1 | 2,
  prompt: string,
  choices: [string | number, string | number, string | number, string | number],
  solution: string,
  hint: string,
): FamilyDraft {
  return {
    skill,
    difficulty,
    prompt,
    choices: choices.map(String) as FamilyDraft["choices"],
    solution,
    hint,
  };
}


export type Question = LessonQuestion & { choiceFeedback?: string[] };

export const TRAINER_BANK_VERSION = 1;
const fmt = (n: number) => String(Number(n.toFixed(8))).replace(".", ",");

/** Parameters are bounded and every generated task has an exact, authored solution. */
export function generatedQuestion(topic: string, i: number): Question {
  const n = i + 2,
    a = 2 + (i % 11),
    b = 3 + (Math.floor(i / 11) % 12);
  let prompt = "",
    solution = "",
    answer = 0;
  const set = (p: string, v: number, s: string) => {
    prompt = p;
    answer = v;
    solution = s;
  };
  switch (topic) {
    case "A05-01":
      if (i % 2)
        set(
          `В ${a} коробках по ${n} карандашей. Сколько карандашей всего?`,
          a * n,
          `Число коробок умножаем на число карандашей: ${a} · ${n} = ${a * n}.`,
        );
      else
        set(
          `Вычисли: ${n * 7 + a} − ${n * 3}.`,
          n * 4 + a,
          `Вычитаем по разрядам: ${n * 7 + a} − ${n * 3} = ${n * 4 + a}. Проверка: ${n * 4 + a} + ${n * 3} = ${n * 7 + a}.`,
        );
      break;
    case "A05-02":
      set(
        `Вычисли: (${n} + ${a}) · ${b} − ${a}.`,
        (n + a) * b - a,
        `Сначала скобки: ${n + a}. Затем умножение: ${(n + a) * b}. После вычитания получаем ${(n + a) * b - a}.`,
      );
      break;
    case "A05-03":
      if (i % 2)
        set(
          `За ${a} ч поезд прошёл ${n * a} км. Какова скорость в км/ч?`,
          n,
          `v = s : t = ${n * a} : ${a} = ${n} км/ч.`,
        );
      else
        set(
          `Станок выпускает ${n} деталей в час. Сколько деталей он выпустит за ${a} ч?`,
          n * a,
          `Работа = производительность × время: ${n} · ${a} = ${n * a} деталей.`,
        );
      break;
    case "A05-04":
      set(
        `Вычисли: |−${n}| − ${a * 2}.`,
        n - a * 2,
        `Модуль −${n} равен ${n}. Поэтому ${n} − ${a * 2} = ${n - a * 2}.`,
      );
      break;
    case "G05-01":
      set(
        `Один из смежных углов равен ${n}°. Сколько градусов в другом?`,
        180 - n,
        `Смежные углы в сумме дают 180°. Второй угол: 180° − ${n}° = ${180 - n}°.`,
      );
      break;
    case "G05-02":
      if (i % 2)
        set(
          `У прямоугольника стороны ${n} см и ${a} см. Найди периметр в см.`,
          2 * (n + a),
          `P = 2(a + b) = 2 · (${n} + ${a}) = ${2 * (n + a)} см.`,
        );
      else
        set(
          `У прямоугольника стороны ${n} см и ${a} см. Найди площадь в см².`,
          n * a,
          `S = ab = ${n} · ${a} = ${n * a} см².`,
        );
      break;
    case "A06-01":
      if (i % 2)
        set(
          `Найди НОД чисел ${2 * n} и ${3 * n}.`,
          n,
          `НОД(2${"·"}${n}, 3${"·"}${n}) = ${n} · НОД(2, 3) = ${n}.`,
        );
      else
        set(
          `Найди НОК чисел ${2 * n} и ${3 * n}.`,
          6 * n,
          `НОД равен ${n}, поэтому НОК = (${2 * n} · ${3 * n}) : ${n} = ${6 * n}.`,
        );
      break;
    case "A06-02":
      if (i % 2)
        set(
          `Сократи дробь ${n * a}/${(n + 1) * a}. Чему равен числитель несократимой дроби?`,
          n,
          `Делим числитель и знаменатель на ${a}: получаем ${n}/${n + 1}. Соседние натуральные числа взаимно просты.`,
        );
      else
        set(
          `Вычисли ${a}/${b} от числа ${n * b}.`,
          n * a,
          `Чтобы найти часть, делим на знаменатель и умножаем на числитель: ${n * b} : ${b} · ${a} = ${n * a}.`,
        );
      break;
    case "A06-03":
      set(
        `Вычисли: ${fmt(n / 10)} · ${a}.`,
        (n * a) / 10,
        `Умножаем ${n} на ${a} и отделяем одну цифру после запятой: ${fmt((n * a) / 10)}.`,
      );
      break;
    case "A06-04":
      set(
        `Найди ${a * 5}% от ${n * 20}.`,
        n * a,
        `Один процент — ${fmt(n / 5)}. Тогда ${a * 5}% = ${n * 20} · ${a * 5} : 100 = ${n * a}.`,
      );
      break;
    case "A06-05":
      if (i % 2)
        set(
          `Зависимость задана формулой y = ${a}x. Найди y при x = ${n}.`,
          a * n,
          `Подставляем x: y = ${a} · ${n} = ${a * n}.`,
        );
      else
        set(
          `Зависимость задана формулой y = ${a * n}/x. Найди y при x = ${a}.`,
          n,
          `При обратной пропорциональности xy = ${a * n}. Поэтому y = ${a * n} : ${a} = ${n}.`,
        );
      break;
    case "A06-06":
      set(
        `Цена ${n * 100} сом снизилась на ${a * 5}%. Какова новая цена в сомах?`,
        n * (100 - a * 5),
        `Скидка: ${n * 100} · ${a * 5} : 100 = ${n * a * 5}. Новая цена: ${n * 100} − ${n * a * 5} = ${n * (100 - a * 5)} сом.`,
      );
      break;
    case "G06-01":
      set(
        `Точка A(${n}; −${a}) сдвинулась на ${b} единиц влево. Найди новую абсциссу x.`,
        n - b,
        `Движение влево уменьшает x: ${n} − ${b} = ${n - b}. Ордината остаётся −${a}.`,
      );
      break;
    case "A07-01":
      set(
        `Найди значение ${a}x + ${b}x − ${a} при x = ${n}.`,
        (a + b) * n - a,
        `Приводим подобные: (${a} + ${b})x − ${a} = ${a + b}x − ${a}. Подставляем x = ${n}: ${(a + b) * n - a}.`,
      );
      break;
    case "A07-02":
      set(
        `Запиши x^${n} · x^${a} в виде одной степени. Чему равен показатель?`,
        n + a,
        `При умножении степеней с одинаковым основанием показатели складываются: ${n} + ${a} = ${n + a}.`,
      );
      break;
    case "A07-03":
      set(
        `Найди коэффициент при x² после раскрытия скобок: (${n}x + ${b})(${a}x − 1).`,
        n * a,
        `Член с x² получается только из ${n}x · ${a}x = ${n * a}x². Коэффициент равен ${n * a}.`,
      );
      break;
    case "A07-04":
      set(
        `Вынеси общий множитель: ${n * a}x + ${n * b} = ${n}(${a}x + c). Найди c.`,
        b,
        `Делим второе слагаемое на вынесенный множитель: c = ${n * b} : ${n} = ${b}.`,
      );
      break;
    case "A07-05":
      set(
        `После раскрытия (${n} + x)² какой коэффициент стоит при x?`,
        2 * n,
        `Квадрат суммы: (${n} + x)² = ${n * n} + ${2 * n}x + x². Удвоенное произведение даёт коэффициент ${2 * n}.`,
      );
      break;
    case "A07-06":
      set(
        `Реши уравнение ${a}x + ${b} = ${a * n + b}.`,
        n,
        `Переносим ${b}: ${a}x = ${a * n}. Делим на ${a}: x = ${n}.`,
      );
      break;
    case "A07-07":
      set(
        `Для функции y = ${a}x − ${b} найди y при x = ${n}.`,
        a * n - b,
        `Подставляем x = ${n}: y = ${a} · ${n} − ${b} = ${a * n - b}.`,
      );
      break;
    case "A07-08":
      set(
        `Реши систему x + y = ${n + a}, x − y = ${n - a}. Найди x.`,
        n,
        `Складываем уравнения: 2x = ${n + a} + (${n - a}) = ${2 * n}. Следовательно, x = ${n}.`,
      );
      break;
    case "G07-01":
      set(
        `В равнобедренном треугольнике угол при вершине ${n}°. Найди угол при основании в градусах.`,
        (180 - n) / 2,
        `Углы при основании равны. На них остаётся 180° − ${n}° = ${180 - n}°. Каждый равен ${fmt((180 - n) / 2)}°.`,
      );
      break;
    case "G07-02":
      set(
        `Две параллельные прямые пересечены секущей. Один внутренний односторонний угол равен ${n}°. Найди второй в градусах.`,
        180 - n,
        `Внутренние односторонние углы при параллельных прямых в сумме равны 180°: 180° − ${n}° = ${180 - n}°.`,
      );
      break;
    case "A08-01":
      set(
        `При x ≠ 0 сократи (${n * a}x)/(${a}x). Чему равно выражение?`,
        n,
        `Общий множитель ${a}x не равен нулю. Сокращаем его: ${n * a} : ${a} = ${n}.`,
      );
      break;
    case "A08-02":
      set(
        `При a ≠ 0 представь a^${n} · a^(−${a}) в виде a^k. Найди k.`,
        n - a,
        `Складываем показатели: k = ${n} + (−${a}) = ${n - a}.`,
      );
      break;
    case "A08-03":
      set(
        `Вычисли √${n * n} + √${a * a}.`,
        n + a,
        `Арифметический квадратный корень неотрицателен: √${n * n} = ${n}, √${a * a} = ${a}. Сумма равна ${n + a}.`,
      );
      break;
    case "A08-04":
      if (i % 2)
        set(
          `По теореме Виета найди сумму корней x² − ${n + a}x + ${n * a} = 0.`,
          n + a,
          `Для x² + bx + c = 0 сумма корней равна −b. Здесь b = −${n + a}, поэтому сумма ${n + a}. Корни ${n} и ${a}.`,
        );
      else
        set(
          `Найди дискриминант x² − ${n + 1}x + ${n} = 0.`,
          (n - 1) ** 2,
          `D = b² − 4ac = ${n + 1}² − 4 · ${n} = ${(n + 1) ** 2} − ${4 * n} = ${(n - 1) ** 2}.`,
        );
      break;
    case "A08-05":
      set(
        `Реши −${a}x < −${a * n}. Получится x > c. Найди c.`,
        n,
        `Делим на отрицательное число −${a} и меняем знак: x > ${n}.`,
      );
      break;
    case "G08-01":
      set(
        `У трапеции основания ${n} см и ${n + 2} см, высота ${a} см. Найди площадь в см².`,
        (n + 1) * a,
        `S = (a + b)h : 2 = (${n} + ${n + 2}) · ${a} : 2 = ${(n + 1) * a} см².`,
      );
      break;
    case "G08-02":
      if (i % 2)
        set(
          `Гипотенуза прямоугольного треугольника ${5 * n} см, катет ${3 * n} см. Найди второй катет в см.`,
          4 * n,
          `b² = ${5 * n}² − ${3 * n}² = ${16 * n * n}. Положительный корень: b = ${4 * n} см.`,
        );
      else
        set(
          `Катеты прямоугольного треугольника ${3 * n} см и ${4 * n} см. Найди гипотенузу в см.`,
          5 * n,
          `c² = ${3 * n}² + ${4 * n}² = ${25 * n * n}. Следовательно, c = ${5 * n} см.`,
        );
      break;
    case "G08-03":
      set(
        `Найди скалярное произведение векторов (${n}; ${a}) и (${b}; −1).`,
        n * b - a,
        `Умножаем соответствующие координаты и складываем: ${n} · ${b} + ${a} · (−1) = ${n * b - a}.`,
      );
      break;
    case "A09-01":
      set(
        `Найди абсциссу вершины параболы y = x² − ${2 * n}x + ${a}.`,
        n,
        `x₀ = −b/(2a). Коэффициент при x² равен 1, при x — −${2 * n}. Поэтому x₀ = ${2 * n}/2 = ${n}.`,
      );
      break;
    case "A09-02":
      set(
        `Сколько целых чисел удовлетворяют (x − ${a})(x − ${a + n}) < 0?`,
        n - 1,
        `Произведение отрицательно строго между корнями: ${a} < x < ${a + n}. Целые числа от ${a + 1} до ${a + n - 1}; всего ${n - 1}.`,
      );
      break;
    case "A09-03":
      set(
        `В уравнении x⁴ − ${n * n + 1}x² + ${n * n} = 0 сделай замену t = x². Найди больший корень t.`,
        n * n,
        `Получаем t² − ${n * n + 1}t + ${n * n} = (t − 1)(t − ${n * n}) = 0. Больший корень t равен ${n * n}.`,
      );
      break;
    case "A09-04":
      set(
        `В арифметической прогрессии a₁ = ${a}, d = ${b}. Найди a${n}.`,
        a + (n - 1) * b,
        `aₙ = a₁ + (n − 1)d = ${a} + (${n} − 1) · ${b} = ${a + (n - 1) * b}.`,
      );
      break;
    case "A09-05":
      set(
        `Вычисли ${n * n}^(1/2).`,
        n,
        `Для положительного основания степень 1/2 — арифметический квадратный корень: √${n * n} = ${n}.`,
      );
      break;
    case "A09-06":
      set(
        `Угол равен ${n}π/180 радиан. Сколько это градусов?`,
        n,
        `π радиан = 180°. Умножаем ${n}π/180 на 180/π: получаем ${n}°.`,
      );
      break;
    case "G09-01":
      set(
        `Сторона первого треугольника ${n} см, соответствующая сторона подобного ему треугольника ${2 * n} см. Периметр первого ${3 * n + 2} см. Найди периметр второго в см.`,
        2 * (3 * n + 2),
        `Коэффициент подобия ${2 * n}/${n} = 2. Периметры относятся так же: 2 · ${3 * n + 2} = ${2 * (3 * n + 2)} см.`,
      );
      break;
    case "G09-02":
      set(
        `Две стороны треугольника равны ${n} см и ${n} см, угол между ними 60°. Найди квадрат третьей стороны в см².`,
        n * n,
        `По теореме косинусов: c² = ${n}² + ${n}² − 2 · ${n} · ${n} · cos 60°. Так как cos 60° = 1/2, c² = ${n * n}.`,
      );
      break;
    case "A10-01":
      set(
        `График y = x² сдвинули вправо на ${n} и вверх на ${a}. Найди ординату вершины нового графика.`,
        a,
        `Новая функция: y = (x − ${n})² + ${a}. Её вершина (${n}; ${a}), поэтому ордината равна ${a}.`,
      );
      break;
    case "A10-02":
      set(
        `Период функции y = sin(${n}x) записали как 2π/k. Найди k.`,
        n,
        `Для sin(kx) наименьший положительный период T = 2π/|k|. Здесь k = ${n}, значит T = 2π/${n}.`,
      );
      break;
    case "A10-03":
      set(
        `Углы измеряются в градусах. Найди arccos(cos ${n}°).`,
        n,
        `Главные значения arccos лежат от 0° до 180°. Угол ${n}° входит в этот промежуток, поэтому ответ ${n}°.`,
      );
      break;
    case "A10-04":
      set(
        `Сколько корней у sin x = 0 на отрезке [0; ${n}π]?`,
        n + 1,
        `Корни имеют вид x = kπ. Здесь k принимает целые значения от 0 до ${n}, включая обе границы. Всего ${n + 1} корней.`,
      );
      break;
    case "A10-05":
      set(
        `Найди предел (${a}x + ${b}) при x → ${n}.`,
        a * n + b,
        `Линейная функция непрерывна. Подставляем предельное значение: ${a} · ${n} + ${b} = ${a * n + b}.`,
      );
      break;
    case "A10-06":
      set(
        `Для f(x) = ${n}x² + ${a}x найди f′(1).`,
        2 * n + a,
        `f′(x) = ${2 * n}x + ${a}. При x = 1 получаем ${2 * n + a}.`,
      );
      break;
    case "A10-07":
      set(
        `В какой точке x функция f(x) = (x − ${n})² + ${a} достигает минимума?`,
        n,
        `f′(x) = 2(x − ${n}). Производная меняет знак с минуса на плюс при x = ${n}; это точка минимума.`,
      );
      break;
    case "G10-01":
      set(
        `На прямой отмечены ${n} различных точек. Точка M не лежит на этой прямой. Сколько различных прямых соединяют M с отмеченными точками?`,
        n,
        `Через M и каждую отмеченную точку проходит единственная прямая. Они различны: иначе M лежала бы на исходной прямой. Всего ${n}.`,
      );
      break;
    case "G10-02":
      set(
        `Из точки A проведён перпендикуляр AH к плоскости: AH = ${3 * n} см. В плоскости HB = ${4 * n} см. Найди наклонную AB в см.`,
        5 * n,
        `AH перпендикулярен любой прямой плоскости через H, значит ∠AHB = 90°. AB² = ${3 * n}² + ${4 * n}² = ${25 * n * n}. AB = ${5 * n} см.`,
      );
      break;
    case "A11-01":
      set(
        `Реши 2^(x + ${a}) = 2^${n + a}.`,
        n,
        `Показательная функция с основанием 2 строго возрастает. Равны показатели: x + ${a} = ${n + a}, откуда x = ${n}.`,
      );
      break;
    case "A11-02":
      set(
        `Вычисли log₂(2^${n}).`,
        n,
        `По определению логарифма logₐ(aᵇ) = b при a > 0 и a ≠ 1. Поэтому ответ ${n}.`,
      );
      break;
    case "A11-03":
      set(
        `Реши log₂(x − ${n}) = 3.`,
        n + 8,
        `ОДЗ: x > ${n}. По определению логарифма x − ${n} = 2³ = 8. x = ${n + 8} удовлетворяет ОДЗ.`,
      );
      break;
    case "A11-04":
      set(
        `Первообразная для f(x) = ${n} имеет вид F(x) = ${n}x + C. При F(0) = ${a} найди F(2).`,
        2 * n + a,
        `Из F(0) = C = ${a}. Значит F(2) = ${n} · 2 + ${a} = ${2 * n + a}.`,
      );
      break;
    case "A11-05":
      set(
        `Вычисли определённый интеграл функции f(x) = 2x от 0 до ${n}.`,
        n * n,
        `Первообразная F(x) = x². По формуле Ньютона–Лейбница: F(${n}) − F(0) = ${n}² − 0 = ${n * n}.`,
      );
      break;
    case "G11-01":
      set(
        `У пирамиды основание — ${n + 2}-угольник. Сколько у неё рёбер?`,
        2 * (n + 2),
        `В основании ${n + 2} рёбер. Ещё ${n + 2} рёбер соединяют вершину пирамиды с вершинами основания. Всего ${2 * (n + 2)}.`,
      );
      break;
    case "G11-02":
      if (i % 2)
        set(
          `Площадь основания пирамиды ${n * 3} см², высота ${a} см. Найди объём в см³.`,
          n * a,
          `V = Sосн · h / 3 = ${n * 3} · ${a} / 3 = ${n * a} см³.`,
        );
      else
        set(
          `Площадь основания призмы ${n} см², высота ${a} см. Найди объём в см³.`,
          n * a,
          `V = Sосн · h = ${n} · ${a} = ${n * a} см³.`,
        );
      break;
    default:
      throw Error(`No trainer generator for ${topic}`);
  }
  const candidates = [answer, answer + 1, answer - 1, answer + a + 1];
  return {
    id: `${topic}-generated-v1-${i}`,
    prompt,
    correct: 0,
    choices: candidates.map(fmt),
    concept: topic,
    hints: ["Открой шпаргалку и выбери правило для этого условия."],
    solution,
    source: "Собственная параметрическая задача Espada.",
  };
}
const banks = new Map<string, Question[]>();
export function trainerBank(topic: string): Question[] {
  if (banks.has(topic)) return banks.get(topic)!;
  if (!trainerTopics[topic]) throw Error("Unknown trainer topic");
  const meta = getLessonMeta(topic);
  const content = getLessonContent({
    lessonId: topic,
    contentVersion: meta.version,
  });
  const authored = [...content.practice, ...content.check].filter(
    (q) =>
      q.choices.length >= 2 &&
      !/самопровер|проверь себя|самостоятельная проверка/i.test(q.prompt),
  );
  const unique = new Map<string, Question>();
  for (const q of [
    ...authored,
    ...Array.from({ length: 144 }, (_, i) => generatedQuestion(topic, i)),
  ])
    if (!unique.has(q.prompt)) unique.set(q.prompt, q);
  const bank = [...unique.values()];
  banks.set(topic, bank);
  return bank;
}
function random(seed: number) {
  return () => {
    seed |= 0;
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
function shuffled<T>(items: T[], seed: number): T[] {
  const result = [...items],
    rng = random(seed);
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}
/** A shuffled cycle has no repeats; a new cycle cannot immediately repeat its boundary question. */
export function trainerQuestion(
  topic: string,
  seed: number,
  cursor: number,
): Question {
  const bank = trainerBank(topic),
    round = Math.floor(cursor / bank.length);
  // Rotate the same permutation between cycles; every cycle still covers the entire bank.
  const order = shuffled(bank, seed);
  const q = order[((cursor % bank.length) + round) % bank.length];
  const options = shuffled(
    q.choices.map((text, id) => ({ text, id })),
    seed + cursor * 31,
  );
  return {
    ...q,
    choices: options.map((x) => x.text),
    correct: options.findIndex((x) => x.id === q.correct),
    choiceFeedback: q.choiceFeedback
      ? options.map((x) => q.choiceFeedback![x.id])
      : undefined,
  };
}

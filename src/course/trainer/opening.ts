export function trainerOpening(topic: string, original: Question): Question {
  if (original.choices.length === 4) return original;
  const extra = fourth[topic];
  if (
    original.choices.length !== 3 ||
    !extra ||
    original.choices.includes(extra)
  )
    throw Error(`Missing opening choice: ${topic}`);
  return { ...original, choices: [...original.choices, extra] };
}
